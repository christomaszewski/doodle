"""ROS side of the service: /diagnostics and the `tx_power` parameter on /<namespace>/radio.

Three activities, so nothing slow blocks anything else:

- a timer publishes a DiagnosticArray every health.interval_s from in-memory state only;
- a poll thread reads the radio every health.poll_interval_s over its own API session;
- `ros2 param set` requests run in their own callback group and may wait while the supervisor
  changes the radio, then answer with the real outcome.

The parameter holds the power target (a level name, `unchanged`, or whole dBm) and follows changes
made with `doodle-up … tx-power`. `off` is refused here: a remote command could switch off the
very link it arrived on. ROS starts in the background and its failures never stop power control:
they are logged and reported in the supervisor status as `diagnostics: failed: …` (which fails the
container health check), as is a ROS start that does not finish within START_TIMEOUT.
"""
from contextlib import contextmanager
import json
import logging
import os
import threading
import time

import doodle_config
from health import HealthReporter
from radio_api import RadioError

LOG = logging.getLogger("doodle.health")
PARAMETER = "tx_power"
START_TIMEOUT = 60  # s; e.g. an RMW waiting for an unreachable Zenoh router
OFF_REFUSED = ("off is refused over ROS (it could switch off the link the request arrived on); "
               "use `doodle-up <config> tx-power off` on the vehicle")


def ros_values(values):
    """DiagnosticStatus values are strings; non-strings keep their JSON spelling (null, false)."""
    return {key: value if isinstance(value, str) else json.dumps(value, allow_nan=False)
            for key, value in values.items()}


def parameter_value(target):
    """The parameter's value for a normalized target: whole dBm stay integers."""
    return target if isinstance(target, int) else str(target)


class ParameterBridge:
    """`tx_power` parameter semantics, independent of rclpy."""

    def __init__(self, controller):
        self.controller = controller

    def set(self, value):
        """-> (accepted, reason). Applies the request; may block while the radio changes."""
        startup = isinstance(value, str) and value.strip().lower() == "startup"
        if not startup:
            try:
                target = doodle_config.power_value(value, PARAMETER)
            except ValueError as error:
                return False, str(error)
            if target == self.controller.target:
                return True, ""  # already the target (also how the parameter follows the launcher)
            if target == "off":
                return False, OFF_REFUSED
        try:
            self.controller.request("startup" if startup else value)
        except RadioError as error:
            # Accepted: the target is saved and the reconcile loop keeps applying it.
            LOG.warning("%s %s accepted but not applied yet: %s", PARAMETER, value, error)
            return True, f"accepted; not applied yet: {error}"
        except (RuntimeError, ValueError) as error:
            return False, str(error)
        return True, ""

    def wanted(self):
        return parameter_value(self.controller.target)


class RosHealth:
    def __init__(self, controller, config, stop_event, radio):
        self.controller, self.stop_event, self.radio = controller, stop_event, radio
        self.namespace = os.environ.get("DOODLE_NAMESPACE") or "/doodle"
        self.reporter = HealthReporter(os.environ.get("DOODLE_NAME") or self.namespace.strip("/"),
                                       os.environ.get("VEHICLE_ID", ""), config["health"])
        self.bridge = ParameterBridge(controller)
        self.context = self.node = self.executor = None
        self.threads = []
        self.spin_stop = threading.Event()
        self.next_warning = 0.0

    def guarded(self, action):
        try:
            action()
        except Exception:
            if time.monotonic() >= self.next_warning:
                LOG.exception("diagnostics step failed; power control continues")
                self.next_warning = time.monotonic() + 60

    def start(self):
        import rclpy
        from rclpy.callback_groups import MutuallyExclusiveCallbackGroup
        from rclpy.clock import Clock, ClockType
        from rclpy.context import Context
        from rclpy.executors import MultiThreadedExecutor
        from rclpy.parameter import Parameter
        from rclpy.signals import SignalHandlerOptions
        from rcl_interfaces.msg import ParameterDescriptor, SetParametersResult
        from diagnostic_msgs.msg import DiagnosticArray, DiagnosticStatus, KeyValue

        levels = (DiagnosticStatus.OK, DiagnosticStatus.WARN, DiagnosticStatus.ERROR,
                  DiagnosticStatus.STALE)  # generated byte constants, not ints (Lyrical)
        self.context = Context()
        # The supervisor owns SIGTERM/SIGINT.
        rclpy.init(args=[], context=self.context, signal_handler_options=SignalHandlerOptions.NO)
        node = self.node = rclpy.create_node(
            "radio", namespace=self.namespace, context=self.context, use_global_arguments=False,
            enable_rosout=False)
        publisher = node.create_publisher(DiagnosticArray, "/diagnostics", 10)
        stamp_clock = Clock(clock_type=ClockType.SYSTEM_TIME)

        node.declare_parameter(PARAMETER, self.bridge.wanted(), ParameterDescriptor(
            description="Transmit power target: standby | low | medium | high | max | "
                        "unchanged | startup | whole dBm. off is refused over ROS.",
            dynamic_typing=True))

        def on_set(parameters):
            for parameter in parameters:
                if parameter.name != PARAMETER:
                    continue
                accepted, reason = self.bridge.set(parameter.value)
                if not accepted:
                    return SetParametersResult(successful=False, reason=reason)
            return SetParametersResult(successful=True)

        node.add_on_set_parameters_callback(on_set)

        def publish():
            message = DiagnosticArray()
            message.header.stamp = stamp_clock.now().to_msg()
            for report in self.reporter.snapshot(self.controller.health_state()):
                row = DiagnosticStatus()
                row.level = levels[report["level"]]
                row.name, row.message = report["name"], report["message"]
                row.hardware_id = report["hardware_id"]
                row.values = [KeyValue(key=k, value=v)
                              for k, v in ros_values(report["values"]).items()]
                message.status.append(row)
            publisher.publish(message)

        def follow_target():
            # Changes made with `doodle-up … tx-power` show up in the parameter.
            wanted = self.bridge.wanted()
            if node.get_parameter(PARAMETER).value != wanted:
                node.set_parameters([Parameter(PARAMETER, value=wanted)])

        def tick():
            self.guarded(follow_target)
            self.guarded(publish)

        # Parameter services use the node's default group; the heartbeat gets its own, so a
        # parameter request waiting on the radio never delays a publication.
        node.create_timer(self.reporter.settings["interval_s"], tick,
                          callback_group=MutuallyExclusiveCallbackGroup())
        self.executor = MultiThreadedExecutor(num_threads=2, context=self.context)
        self.executor.add_node(node)

        def spin():
            while not self.spin_stop.is_set():
                self.guarded(lambda: self.executor.spin_once(timeout_sec=0.2))

        def poll():
            interval = self.reporter.settings["poll_interval_s"]
            while not self.stop_event.is_set():
                self.guarded(lambda: self.reporter.poll(self.radio))
                self.stop_event.wait(interval)

        for target, name in ((spin, "doodle-ros"), (poll, "doodle-health-poll")):
            thread = threading.Thread(target=target, name=name, daemon=True)
            thread.start()
            self.threads.append(thread)
        LOG.info("publishing /diagnostics every %gs; parameter %s/radio %s",
                 self.reporter.settings["interval_s"], self.namespace.rstrip("/"), PARAMETER)

    def stop(self):
        self.spin_stop.set()
        if self.executor is not None:
            self.executor.wake()
        for thread in self.threads:
            # A poll can be inside one bounded radio request; it is a daemon either way.
            thread.join(timeout=5)
        if self.executor is not None:
            self.executor.shutdown(timeout_sec=5)
        if self.node is not None:
            self.node.destroy_node()
        if self.context is not None:
            self.context.try_shutdown()


@contextmanager
def ros_health(controller, config, stop_event, radio, *, start_timeout=START_TIMEOUT):
    """Start diagnostics without making power control wait for ROS."""
    health = RosHealth(controller, config, stop_event, radio)
    controller.diagnostics = "starting"

    def launch():
        try:
            health.start()
            controller.diagnostics = "publishing"
        except Exception as error:
            LOG.exception("diagnostics unavailable; power control continues without them")
            controller.diagnostics = f"failed: {error}"
            try:
                health.stop()
            except Exception:
                LOG.exception("cleaning up after the failed diagnostics start")

    def overdue():
        if controller.diagnostics == "starting":
            controller.diagnostics = (f"failed: ROS did not start within {start_timeout}s "
                                      "(check RMW_IMPLEMENTATION and the Zenoh router)")
            LOG.error("%s", controller.diagnostics)

    starter = threading.Thread(target=launch, name="doodle-ros-start", daemon=True)
    watchdog = threading.Timer(start_timeout, overdue)
    watchdog.daemon = True
    starter.start()
    watchdog.start()
    try:
        yield
    finally:
        watchdog.cancel()
        starter.join(timeout=5)
        if not starter.is_alive() and controller.diagnostics == "publishing":
            health.stop()  # a start still hanging is abandoned (daemon threads)
